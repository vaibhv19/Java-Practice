package com.JavaFundamentals.Basics;

/**
 * HelloWorld demonstrates the fundamental structure of a Java application.
 * Topics covered:
 * - Public class declaration
 * - main method signature (public static void main(String[] args))
 * - System.out.println output
 */
public class HelloWorld {
    public static void main(String[] args) {
        System.out.println("Hello, World!");
        System.out.println("Welcome to Java Programming.");
        
        // Demonstrating basic output and program execution entry point
        int a = 10;
        int b = 20;
        int sum = a + b;
        System.out.println("Sum of " + a + " and " + b + " is: " + sum);
    }
}
